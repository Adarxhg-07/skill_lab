/* --- Badge Rendering --- */
function priorityBadge(priority) {
  const map = {
    low: 'badge--muted',
    medium: 'badge--warning',
    high: 'badge--danger'
  };
  return `<span class="badge ${map[priority] || 'badge--muted'}">${priority}</span>`;
}

function statusBadge(status) {
  const map = {
    'todo': ['badge--muted', 'To Do'],
    'in-progress': ['badge--accent', 'In Progress'],
    'done': ['badge--success', 'Done']
  };
  const [cls, label] = map[status] || ['badge--muted', status];
  return `<span class="badge ${cls}">${label}</span>`;
}

/* --- Student Name Lookup --- */
let allStudentsCache = [];

function setStudentsCache(students) {
  if (Array.isArray(students)) {
    allStudentsCache = students;
  }
}

function getStudentName(student) {
  if (!student) return 'Unassigned';
  if (typeof student === 'object' && student.name) {
    return student.name;
  }
  const id = typeof student === 'object' ? student._id : student;
  const found = allStudentsCache.find(s => s._id === id);
  if (found) return found.name;
  const mock = MOCK_STUDENTS.find(s => s._id === id);
  return mock ? mock.name : 'Unassigned';
}

/* --- Debounce --- */
function debounce(fn, delay = 300) {
  let timer;
  return (...args) => {
    clearTimeout(timer);
    timer = setTimeout(() => fn(...args), delay);
  };
}

